export function dailyGameOf(dateStr: string): DailyGame {
  let h = 0;
  for (let i = 0; i < dateStr.length; i++) h = (h * 31 + dateStr.charCodeAt(i)) % 100000;
  return DAILY_GAMES[h % DAILY_GAMES.length];
}
